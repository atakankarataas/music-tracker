"""Prepare a single-file Supabase Dashboard deployment from tested modules.

No secrets are included. The result is gitignored in reports/.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
folder = ROOT / 'supabase/functions/spotify-sync'
core = (folder / 'core.ts').read_text()
storage = (folder / 'storage.ts').read_text()
index = (folder / 'index.ts').read_text()
def local_imports(source):
    return re.sub(r'^import\s(?:type\s)?[^;]*?\sfrom\s[\"\']\./(?:core|storage)\.ts[\"\'];\s*', '', source, flags=re.M)

storage = local_imports(storage)
index = local_imports(index)
output = ROOT / 'reports/spotify-sync-deploy.ts'
output.parent.mkdir(exist_ok=True)
output.write_text('// Generated by scripts/bundle-edge.py; edit the source modules.\n' + core + '\n' + storage + '\n' + index)
print('Prepared:', output)
